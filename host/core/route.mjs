/**
 * L1 core — route vocabulary. Pure: no `ctx`, no DOM, no I/O.
 * Everything the Harness needs to know about a route decision lives here.
 */
import { CONTEXT_SUMMARY_MAX_CHARS } from '../contracts.mjs';

/** A route is exactly the three fields; an absent effort means "provider default". */
export function isRoute(value) {
    return value !== null && typeof value === 'object'
        && typeof value.provider === 'string' && value.provider.length > 0
        && typeof value.model === 'string' && value.model.length > 0;
}

/** Route equality: absent and `undefined` reasoningEffort are the same value. */
export function sameRoute(left, right) {
    return left !== undefined && right !== undefined
        && left.provider === right.provider
        && left.model === right.model
        && (left.reasoningEffort ?? undefined) === (right.reasoningEffort ?? undefined);
}

/** Label `route` relative to `other`: same provider prints the model alone. */
export function routeLabel(route, other) {
    return route.provider === other.provider ? route.model : `${route.provider}/${route.model}`;
}

/** One line, at most `CONTEXT_SUMMARY_MAX_CHARS`, ellipsis included. */
export function boundSummary(summary) {
    return summary.length <= CONTEXT_SUMMARY_MAX_CHARS
        ? summary
        : `${summary.slice(0, CONTEXT_SUMMARY_MAX_CHARS - 1)}…`;
}

/** `model/selection` payload: never carry an explicit empty effort. */
export function modelSelectionData(route) {
    return {
        provider: route.provider,
        model: route.model,
        ...(route.reasoningEffort === undefined ? {} : { reasoningEffort: route.reasoningEffort }),
    };
}

/**
 * The durable in-conversation switch notice: field-for-field the value
 * `createUserMessage` (@deepseek-ai/dsh-llm) produces for this source, so the
 * transcript row and its `model-selection` source stay canonical without
 * importing the framework. `id` is injected so this function stays pure.
 */
export function modelSwitchNotice(previous, selected, id) {
    const from = routeLabel(previous, selected);
    const to = routeLabel(selected, previous);
    return Object.freeze({
        id,
        role: 'user',
        content: Object.freeze([
            Object.freeze({
                type: 'text',
                text: `[model changed: assistant turns above this point were generated by ${from}; the session continues with ${to}]`,
            }),
        ]),
        source: Object.freeze({
            kind: 'model-selection',
            form: 'notice',
            summary: boundSummary(`${from} → ${to}`),
        }),
    });
}
